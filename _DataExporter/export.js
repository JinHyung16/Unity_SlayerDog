// 경로 기반 모듈 DB(트리형) -> Unity JSON + C# enum
//
// 소스 포맷은 확장자로 정해진다. 새 포맷을 지원하려면 SOURCE_EXTENSIONS 에 확장자를 넣고
// WORKBOOK_LOADERS 에 읽는 함수를 하나 추가하면 된다. (레퍼런스 프로젝트와 같은 방식)
//   '.js'   Node    module.exports = 객체 (함수면 ctx 를 받아 객체를 만든다)
//   '.json' JSON    파일 내용 그대로
//
// 파일 경로(확장자 제외) = 모듈 ID 라서, 같은 모듈을 확장자만 바꿔 옮겨도 참조가 그대로 물린다.

const fs = require('fs');
const path = require('path');

const { Composer } = require('./compose');

const LOG_PREFIX = {
    info: '[INFO]',
    success: '[OK]',
    warning: '[WARN]',
    error: '[ERROR]',
    debug: '[DEBUG]'
};

// 순서가 곧 우선순위다 (_enums 를 찾을 때 앞에서부터 본다)
const SOURCE_EXTENSIONS = ['.js', '.cjs', '.json'];

const WORKBOOK_LOADERS = {
    '.js': loadJsModule,
    '.cjs': loadJsModule,
    '.json': loadJsonFile
};

function loadJsModule(filePath, ctx)
{
    // 한 번 실행하고 끝나는 CLI 지만, watch 모드를 붙일 때를 대비해 캐시를 비운다
    delete require.cache[require.resolve(filePath)];

    const loaded = require(filePath);
    const data = (typeof loaded === 'function') ? loaded(ctx) : loaded;

    if (typeof data !== 'object' || data === null)
    {
        throw new Error('module.exports 가 객체가 아닙니다');
    }
    return data;
}

function loadJsonFile(filePath)
{
    const raw = fs.readFileSync(filePath, 'utf8');
    // BOM 제거 — 윈도우 툴이 뱉은 JSON이 자주 물고 온다
    return JSON.parse(raw.replace(/^﻿/, ''));
}

function readSource(filePath, ctx)
{
    const loader = WORKBOOK_LOADERS[path.extname(filePath).toLowerCase()];
    if (!loader)
    {
        return null;
    }

    const data = loader(filePath, ctx || {});
    if (data === null || data === undefined)
    {
        throw new Error(`빈 값을 반환했습니다: ${filePath}`);
    }
    return data;
}

function isSupported(filePath)
{
    return Object.prototype.hasOwnProperty.call(WORKBOOK_LOADERS, path.extname(filePath).toLowerCase());
}

function ensureDir(dir)
{
    if (fs.existsSync(dir) === false)
    {
        fs.mkdirSync(dir, { recursive: true });
    }
}

function generateGuid()
{
    return 'xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx'.replace(/x/g, () => (Math.random() * 16 | 0).toString(16));
}

function metaContent()
{
    return `fileFormatVersion: 2
guid: ${generateGuid()}
TextScriptImporter:
  externalObjects: {}
  userData:
  assetBundleName:
  assetBundleVariant:
`;
}

/**
 * 테이블 하나를 JSON 파일로 쓴다. 내용이 같으면 건드리지 않는다
 * (Unity 가 불필요하게 리임포트하는 걸 막는다).
 */
function writeJson(outputDir, tableName, data, options)
{
    ensureDir(outputDir);

    const filePath = path.join(outputDir, `${tableName}.json`);
    const text = JSON.stringify(data, null, 4);

    if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === text)
    {
        return { written: false, filePath: filePath };
    }

    fs.writeFileSync(filePath, text, 'utf8');

    if (options && options.generateMeta === true)
    {
        const metaPath = filePath + '.meta';
        if (fs.existsSync(metaPath) === false)
        {
            fs.writeFileSync(metaPath, metaContent(), 'utf8');
        }
    }

    return { written: true, filePath: filePath };
}

/**
 * _enums 소스 -> C# enum 파일 하나.
 */
function writeEnums(csOutputPath, namespaceName, enums)
{
    if (!csOutputPath)
    {
        return null;
    }

    ensureDir(csOutputPath);

    const lines = [];
    lines.push('// <auto-generated />');
    lines.push('// _DataExporter 가 GameData/_enums 에서 생성한 파일입니다. 수동 편집 금지.');
    lines.push('');
    lines.push(`namespace ${namespaceName}`);
    lines.push('{');

    const names = Object.keys(enums);
    for (let i = 0; i < names.length; i++)
    {
        const name = names[i];
        lines.push(`    public enum ${name}`);
        lines.push('    {');
        const members = enums[name];
        for (let m = 0; m < members.length; m++)
        {
            lines.push(`        ${members[m]}${m < members.length - 1 ? ',' : ''}`);
        }
        lines.push('    }');
        if (i < names.length - 1)
        {
            lines.push('');
        }
    }

    lines.push('}');
    const text = lines.join('\r\n') + '\r\n';

    const filePath = path.join(csOutputPath, 'GameEnum.Generated.cs');
    if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === text)
    {
        return { written: false, filePath: filePath, count: names.length };
    }

    fs.writeFileSync(filePath, text, 'utf8');
    return { written: true, filePath: filePath, count: names.length };
}

// C# 자료형 -> JsonValue 읽기 표현. 여기 없는 타입은 enum 으로 본다.
const CS_READERS = {
    'int': (json) => `row.GetInt("${json}")`,
    'float': (json) => `row.GetFloat("${json}")`,
    'bool': (json) => `row["${json}"].AsBool()`,
    'string': (json) => `row.GetString("${json}")`
};

/**
 * 평면 테이블(buff/debuff 등)의 C# 데이터 클래스를 생성한다.
 *
 * 손으로 쓰던 필드 목록 + 파싱 코드를 DB 스키마(config 의 columns)에서 뽑는다.
 * 컬럼을 추가할 때 C# 을 같이 고쳐야 하는 상태를 없애기 위한 것.
 * 타입명·네임스페이스를 기존과 동일하게 유지하므로 호출부는 바뀌지 않는다.
 */
function writeDataClass(outputPath, namespaceName, enumNamespace, spec)
{
    if (!outputPath || !spec.csClass || Array.isArray(spec.columns) === false)
    {
        return null;
    }

    ensureDir(outputPath);

    const lines = [];
    lines.push('// <auto-generated />');
    lines.push(`// _DataExporter 가 config.json 의 '${spec.table}' 스키마에서 생성한 파일입니다. 수동 편집 금지.`);
    lines.push('');
    lines.push(`using ${enumNamespace};`);
    lines.push(`using ${enumNamespace}.Json;`);
    lines.push('');
    lines.push(`namespace ${namespaceName}`);
    lines.push('{');
    lines.push('');
    lines.push(`    public class ${spec.csClass}`);
    lines.push('    {');

    for (const col of spec.columns)
    {
        const isString = col.type === 'string';
        lines.push(`        public ${col.type} ${col.name}${isString ? ' = string.Empty' : ''};`);
    }

    lines.push('');
    lines.push('        /// <summary>JSON 한 행을 읽어 채운다. 실패한 필드는 기본값으로 남는다.</summary>');
    lines.push(`        public static ${spec.csClass} FromJson(JsonValue row)`);
    lines.push('        {');
    lines.push(`            ${spec.csClass} data = new ${spec.csClass}();`);

    for (const col of spec.columns)
    {
        const reader = CS_READERS[col.type];
        if (reader)
        {
            lines.push(`            data.${col.name} = ${reader(col.json)};`);
            continue;
        }
        // enum 은 실패해도 0번(None/기본)으로 두고 계속 간다
        lines.push(`            if (System.Enum.TryParse(row.GetString("${col.json}"), false, out ${col.type} ${col.name.toLowerCase()}Parsed))`);
        lines.push(`                data.${col.name} = ${col.name.toLowerCase()}Parsed;`);
    }

    lines.push('            return data;');
    lines.push('        }');
    lines.push('    }');
    lines.push('}');

    const text = lines.join('\r\n') + '\r\n';
    const filePath = path.join(outputPath, `${spec.csClass}.Generated.cs`);

    if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === text)
    {
        return { written: false, filePath: filePath };
    }

    fs.writeFileSync(filePath, text, 'utf8');
    return { written: true, filePath: filePath };
}

class Exporter
{
    constructor(options)
    {
        this._verbose = options.verbose === true;
        this._rootDir = __dirname;

        this._configPath = options.configPath || path.join(this._rootDir, 'config.json');
        this._config = JSON.parse(fs.readFileSync(this._configPath, 'utf8'));

        this._sourceRoot = options.sourceRoot || path.resolve(this._rootDir, this._config.SourceRoot);
        this._jsonOutputPath = options.jsonOutputPath || path.resolve(this._rootDir, this._config.JsonOutputPath);
        this._csOutputPath = options.csOutputPath || path.resolve(this._rootDir, this._config.CsOutputPath);

        this._excludePrefix = this._config.ExcludePrefix || '_';
        this._excludePatterns = this._config.ExcludePatterns || [];
    }

    log(message, type)
    {
        const kind = type || 'info';
        if (kind === 'debug' && this._verbose === false)
        {
            return;
        }
        console.log(`${LOG_PREFIX[kind] || LOG_PREFIX.info} ${message}`);
    }

    _isExcluded(name)
    {
        if (this._excludePrefix && name.startsWith(this._excludePrefix))
        {
            return true;
        }
        return this._excludePatterns.some(pattern =>
        {
            const regex = new RegExp('^' + pattern.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*') + '$', 'i');
            return regex.test(name);
        });
    }

    _walk(absDir, found)
    {
        for (const entry of fs.readdirSync(absDir, { withFileTypes: true }))
        {
            if (this._isExcluded(entry.name))
            {
                this.log(`제외됨: ${path.relative(this._sourceRoot, path.join(absDir, entry.name))}`, 'debug');
                continue;
            }

            const absPath = path.join(absDir, entry.name);

            if (entry.isDirectory())
            {
                this._walk(absPath, found);
                continue;
            }

            if (isSupported(absPath) === false)
            {
                this.log(`지원하지 않는 확장자 (건너뜀): ${path.relative(this._sourceRoot, absPath)}`, 'debug');
                continue;
            }

            const rel = path.relative(this._sourceRoot, absPath).split(path.sep).join('/');
            found.push({
                id: rel.slice(0, rel.length - path.extname(rel).length),
                filePath: absPath,
                rel: rel
            });
        }
    }

    /**
     * dir 이하를 재귀 스캔해 Map<id, { id, rel, data }> 로 읽어들인다.
     * 폴더 = 모듈 종류, 파일 = 모듈 하나, 파일 경로(확장자 제외) = 모듈 ID.
     * 같은 ID 가 확장자만 다르게 두 번 나오면 즉시 에러 — 어느 쪽이 이겼는지 모르는 상태가 제일 위험하다.
     */
    load(dir, ctx)
    {
        const absDir = path.join(this._sourceRoot, dir);
        if (fs.existsSync(absDir) === false)
        {
            this.log(`폴더가 없습니다 (건너뜀): ${dir}`, 'warning');
            return new Map();
        }

        const found = [];
        this._walk(absDir, found);
        found.sort((a, b) => a.id.localeCompare(b.id));

        const result = new Map();
        for (const entry of found)
        {
            if (result.has(entry.id))
            {
                throw new Error(`모듈 ID 충돌: '${entry.id}' 가 '${result.get(entry.id).rel}' 와 '${entry.rel}' 양쪽에 있습니다`);
            }

            let data;
            try
            {
                data = readSource(entry.filePath, ctx);
            }
            catch (error)
            {
                throw new Error(`읽기 실패 (${entry.rel}): ${error.message}`);
            }

            result.set(entry.id, { id: entry.id, rel: entry.rel, data: data });
        }
        return result;
    }

    /**
     * SourceRoot 바로 아래의 _enums.<지원확장자> 를 찾아 읽는다.
     * '_' 접두사라 일반 스캔에서는 제외되므로 여기서 직접 집는다.
     */
    _loadEnums()
    {
        const baseName = this._config.EnumFile || '_enums';

        for (const ext of SOURCE_EXTENSIONS)
        {
            const candidate = path.join(this._sourceRoot, baseName + ext);
            if (fs.existsSync(candidate) === false)
            {
                continue;
            }

            const raw = readSource(candidate, {});
            const enums = {};

            for (const name of Object.keys(raw))
            {
                const members = raw[name];
                if (Array.isArray(members) === false)
                {
                    throw new Error(`${baseName}${ext}: '${name}' 이 문자열 배열이 아닙니다`);
                }
                // None 은 파싱 실패 시 폴백으로 쓰이므로 항상 0번이어야 한다
                enums[name] = members[0] === 'None' ? members.slice() : ['None'].concat(members);
            }

            this.log(`enum 로드: ${baseName}${ext} (${Object.keys(enums).length}개)`, 'debug');
            return enums;
        }

        throw new Error(`enum 정의 파일을 찾을 수 없습니다: ${path.join(this._sourceRoot, baseName)}.*`);
    }

    /**
     * 모듈 원본을 그대로 JSON 으로 내보내기 위한 정리.
     * 함수(레벨 곡선 등)는 직렬화가 안 되므로 표식만 남긴다.
     */
    _sanitize(value)
    {
        if (typeof value === 'function')
        {
            return '<function>';
        }
        if (Array.isArray(value))
        {
            return value.map(item => this._sanitize(item));
        }
        if (value !== null && typeof value === 'object')
        {
            const out = {};
            for (const key of Object.keys(value))
            {
                out[key] = this._sanitize(value[key]);
            }
            return out;
        }
        return value;
    }

    /**
     * idTable 모듈(버프/디버프 등)은 런타임이 숫자 id 로 조회한다.
     * id 중복이나 enum 오타는 여기서 잡아야 런타임에 조용히 null 이 되는 걸 막는다.
     */
    _validateIdTable(kind, spec, loaded, enums, errors)
    {
        const seen = new Map();

        for (const item of loaded.values())
        {
            const id = Number(item.data.id);
            if (!Number.isFinite(id) || id <= 0)
            {
                errors.push(`${item.rel}: id 가 없거나 유효하지 않습니다 (${JSON.stringify(item.data.id)})`);
                continue;
            }
            if (seen.has(id))
            {
                errors.push(`${item.rel}: ${kind} id ${id} 가 '${seen.get(id)}' 와 중복됩니다`);
                continue;
            }
            seen.set(id, item.rel);

            if (spec.typeEnum)
            {
                const members = enums[spec.typeEnum];
                if (!members)
                {
                    errors.push(`config 의 typeEnum '${spec.typeEnum}' 이 _enums 에 없습니다`);
                }
                else if (members.includes(item.data.type) === false)
                {
                    errors.push(`${item.rel}: ${spec.typeEnum} 에 없는 type: '${item.data.type}'`);
                }
            }

            if (spec.stackEnum)
            {
                const modes = enums[spec.stackEnum];
                const mode = item.data.stackMode;
                if (modes && modes.includes(mode) === false)
                {
                    errors.push(`${item.rel}: ${spec.stackEnum} 에 없는 stackMode: '${mode}'`);
                }

                const maxStacks = Number(item.data.maxStacks);
                if (!Number.isFinite(maxStacks) || maxStacks < 1)
                {
                    errors.push(`${item.rel}: maxStacks 는 1 이상이어야 합니다 (${JSON.stringify(item.data.maxStacks)})`);
                }
                else if (mode !== 'Stack' && maxStacks !== 1)
                {
                    // Refresh/Ignore 인데 maxStacks 가 2 이상이면 의도가 안 맞는 것이다
                    errors.push(`${item.rel}: stackMode '${mode}' 에는 maxStacks 1 만 의미가 있습니다 (현재 ${maxStacks})`);
                }
            }
        }
    }

    run()
    {
        this.log(`지원 확장자: ${SOURCE_EXTENSIONS.join(', ')}`);
        this.log(`소스: ${this._sourceRoot}`);
        this.log(`JSON 출력: ${this._jsonOutputPath}`);
        this.log(`CS  출력: ${this._csOutputPath}`);
        console.log('');

        const enums = this._loadEnums();

        // 1) 모듈 로드 (경로 = ID)
        const moduleDirs = {};
        const modules = {};
        const moduleErrors = [];

        for (const kind of Object.keys(this._config.Modules))
        {
            const spec = this._config.Modules[kind];
            moduleDirs[kind] = spec.dir;
            modules[kind] = this.load(spec.dir, { enums: enums });
            this.log(`모듈 '${kind}' ${modules[kind].size}개 로드 (${spec.dir})`, 'success');

            if (spec.idTable === true)
            {
                this._validateIdTable(kind, spec, modules[kind], enums, moduleErrors);
            }
        }

        // 2) 스킬 로드 + 조립
        //
        // Master 한 장이 「이 스킬 = Method A + Visual B」를 조합한다.
        // Visual 은 스킬과 **같은 이름**으로 Skill/Visual 에 있다 — 이름이 곧 연결이라
        // Master 에 visual 을 적을 필요가 없다.
        const entrySpec = this._config.Entries.skill;
        const entries = this.load(entrySpec.dir, { enums: enums });
        this.log(`스킬 ${entries.size}개 로드 (${entrySpec.dir})`, 'success');

        const composer = new Composer(enums, modules, this._config, this.log.bind(this));
        composer.errors.push(...moduleErrors);
        const skills = [];
        const seenIds = new Map();

        for (const entry of entries.values())
        {
            const record = composer.compose(entry, moduleDirs);
            if (record === null)
            {
                continue;
            }
            if (seenIds.has(record.id))
            {
                composer.errors.push(`${entry.rel}: 스킬 id ${record.id} 가 '${seenIds.get(record.id)}' 와 중복됩니다`);
                continue;
            }
            seenIds.set(record.id, entry.rel);
            skills.push(record);
        }

        skills.sort((a, b) => a.id - b.id);

        // 3) 검증 실패 시 아무것도 쓰지 않고 중단 — 반쯤 갱신된 출력이 제일 나쁘다
        if (composer.errors.length > 0)
        {
            console.log('');
            this.log(`검증 실패 ${composer.errors.length}건 — 출력하지 않았습니다`, 'error');
            for (const message of composer.errors)
            {
                this.log(`  ${message}`, 'error');
            }
            return false;
        }

        // 4) 출력
        const meta = { generateMeta: this._config.GenerateMetaFiles === true };
        let writtenCount = 0;

        for (const kind of Object.keys(this._config.Modules))
        {
            const spec = this._config.Modules[kind];
            // idTable 이면 런타임 조회 키인 숫자 id 가 앞, 경로는 참고용으로 따라간다.
            const rows = [...modules[kind].values()].map(item => spec.idTable === true
                ? Object.assign({ id: Number(item.data.id), path: item.id }, this._sanitize(item.data), { id: Number(item.data.id) })
                : Object.assign({ path: item.id }, this._sanitize(item.data)));

            const result = writeJson(this._jsonOutputPath, spec.table, rows, meta);
            this.log(`${spec.table}.json (${rows.length}행)${result.written ? '' : ' — 변경 없음'}`, result.written ? 'success' : 'debug');
            if (result.written)
            {
                writtenCount++;
            }
        }

        const skillResult = writeJson(this._jsonOutputPath, entrySpec.table, skills, meta);
        this.log(`${entrySpec.table}.json (${skills.length}행)${skillResult.written ? '' : ' — 변경 없음'}`, skillResult.written ? 'success' : 'debug');
        if (skillResult.written)
        {
            writtenCount++;
        }

        // 도구가 만든 «중간 형식»을 그대로 옮긴다.
        //
        // 성좌 그래프처럼 사람이 표에 적는 것이 아니라 도구로 그리는 데이터가 있다.
        // 그 도구가 최종 위치에 직접 쓰게 하면 「도구로 만든 것」과 「손으로 고친 것」이
        // 서로 다른 경로로 들어가 결과가 갈린다. 도구는 SSOT 에만 쓰고, 옮기는 것은 여기 한 곳이다.
        for (const kind of Object.keys(this._config.RawTables || {}))
        {
            const spec = this._config.RawTables[kind];
            const srcPath = path.join(this._sourceRoot, spec.file);

            if (fs.existsSync(srcPath) === false)
            {
                this.log(`${spec.table} — 원본이 없어 건너뜀 (${spec.file})`, 'debug');
                continue;
            }

            let raw;
            try
            {
                raw = loadJsonFile(srcPath);
            }
            catch (error)
            {
                this.log(`${spec.table} 읽기 실패 — ${error.message}`, 'error');
                return false;
            }

            // 비어 있는 입력은 거부한다. 통과시키면 다음 실행에서 데이터가 통째로 사라진다.
            const rowCount = Array.isArray(raw) ? raw.length : (raw.nodes ? raw.nodes.length : 0);
            if (rowCount === 0)
            {
                this.log(`${spec.table} 이 비어 있어 옮기지 않았습니다`, 'error');
                return false;
            }

            const rawResult = writeJson(this._jsonOutputPath, spec.table, raw, meta);
            this.log(`${spec.table}.json (${rowCount}행)${rawResult.written ? '' : ' — 변경 없음'}`, rawResult.written ? 'success' : 'debug');
            if (rawResult.written)
            {
                writtenCount++;
            }
        }

        // 평면 테이블의 C# 데이터 클래스
        const dataOut = this._config.CsDataOutputPath
            ? path.resolve(this._rootDir, this._config.CsDataOutputPath)
            : null;

        for (const kind of Object.keys(this._config.Modules))
        {
            const spec = this._config.Modules[kind];
            const result = writeDataClass(dataOut, this._config.CsDataNamespace, this._config.CsNamespace, spec);
            if (result === null)
            {
                continue;
            }
            this.log(`${spec.csClass}.Generated.cs${result.written ? '' : ' — 변경 없음'}`, result.written ? 'success' : 'debug');
            if (result.written)
            {
                writtenCount++;
            }
        }

        const enumResult = writeEnums(this._csOutputPath, this._config.CsNamespace, enums);
        if (enumResult)
        {
            this.log(`GameEnum.Generated.cs (enum ${enumResult.count}개)${enumResult.written ? '' : ' — 변경 없음'}`, enumResult.written ? 'success' : 'debug');
        }

        console.log('');
        this.log(`완료 — 스킬 ${skills.length}개, 갱신된 파일 ${writtenCount}개`, 'success');
        return true;
    }
}

function main()
{
    const args = process.argv.slice(2);
    const command = args.find(arg => arg.startsWith('-') === false) || 'all';

    if (command === 'help')
    {
        console.log(`
Jinhyeong Skill DB Exporter

사용법:
  node export.js [all|help] [--verbose]

동작:
  GameData/ 트리를 스캔해 모듈(visual/launch/stat/buff/debuff)과 스킬을 읽고,
  슬롯·토큰을 해석해 완성된 스킬 트리 JSON 과 C# enum 을 출력한다.

소스 포맷 확장:
  SOURCE_EXTENSIONS 에 확장자를 넣고 WORKBOOK_LOADERS 에 읽는 함수를 추가한다.
  현재 지원: ${SOURCE_EXTENSIONS.join(', ')}

환경변수:
  SOURCE_ROOT / JSON_OUTPUT_PATH / CS_OUTPUT_PATH / CONFIG_PATH
        `);
        return;
    }

    if (command !== 'all')
    {
        console.log(`알 수 없는 명령어: ${command} ('node export.js help' 참고)`);
        process.exitCode = 1;
        return;
    }

    const options = {
        verbose: args.includes('--verbose') || args.includes('-v'),
        configPath: process.env.CONFIG_PATH || null,
        sourceRoot: process.env.SOURCE_ROOT || null,
        jsonOutputPath: process.env.JSON_OUTPUT_PATH || null,
        csOutputPath: process.env.CS_OUTPUT_PATH || null
    };

    try
    {
        const exporter = new Exporter(options);
        if (exporter.run() === false)
        {
            process.exitCode = 1;
        }
    }
    catch (error)
    {
        console.log(`${LOG_PREFIX.error} ${error.message}`);
        if (options.verbose)
        {
            console.log(error.stack);
        }
        process.exitCode = 1;
    }
}

if (require.main === module)
{
    main();
}

module.exports = Exporter;
